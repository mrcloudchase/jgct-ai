#!/usr/bin/env python3
"""Rebuild knowledge/INDEX.md (one line per record) and the ledger-derived section of sources/INDEX.md.

  python3 tools/build_index.py

knowledge/INDEX.md is fully generated. sources/INDEX.md: everything above the marker
line '<!-- LEDGER-SNAPSHOT -->' is hand-maintained (source catalogue); everything below
is regenerated from the ledger.
"""
import glob, os, sqlite3
import yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MARK = "<!-- LEDGER-SNAPSHOT -->"


SPLIT_AT = 300  # CLAUDE.md: split INDEX.md into topic indexes past ~300 lines


def _line(stem, r, rel="records"):
    flags = (" RETRACTED" if r.get("retracted") else "") + (" [conflicts: " + ", ".join(r["conflicts_with"]) + "]" if r.get("conflicts_with") else "")
    return (f"- [{stem}]({rel}/{stem}.yaml) | {r['year']} | {r['study_type']} | {r.get('tumor_site') or '-'} | {r['source_tier']}"
            f" | n={r.get('n_jgct_patients')} | {r.get('first_author') or ''} | {r['title'][:140]}{flags}")


def knowledge_index():
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, "knowledge/records/*.yaml"))):
        r = yaml.safe_load(open(f)); stem = os.path.basename(f)[:-5]
        rows.append((r.get("study_type"), -r.get("year", 0), stem, r))
    rows.sort(key=lambda x: (x[0], x[1]))
    legend = "One line per record: record id | year | study type | tumor site | tier | n JGCT | first author | title."
    groups = {}
    for st, _, stem, r in rows:
        groups.setdefault(st, []).append((stem, r))
    idx_dir = os.path.join(ROOT, "knowledge/index")
    if len(rows) + 4 * len(groups) + 5 <= SPLIT_AT:
        out = ["# Knowledge base index", "", "Generated by `tools/build_index.py`. " + legend, f"Total records: {len(rows)}", ""]
        for st, items in groups.items():
            out += ["", f"## {st}", ""] + [_line(s, r) for s, r in items]
        for f in glob.glob(os.path.join(idx_dir, "*.md")):
            os.remove(f)
    else:
        os.makedirs(idx_dir, exist_ok=True)
        for f in glob.glob(os.path.join(idx_dir, "*.md")):
            os.remove(f)
        out = ["# Knowledge base index", "", "Generated by `tools/build_index.py`. The base passed ~300 lines, so records are listed in topic indexes by study type under `index/`.",
               f"Total records: {len(rows)}", "", "| topic index | records | ovary | testis | both | other/unstated |", "|---|---|---|---|---|---|"]
        for st, items in groups.items():
            sites = [r.get("tumor_site") for _, r in items]
            out.append(f"| [{st}](index/{st}.md) | {len(items)} | {sites.count('ovary')} | {sites.count('testis')} | {sites.count('both')} | {len(sites) - sites.count('ovary') - sites.count('testis') - sites.count('both')} |")
            sub = [f"# Knowledge base index: {st}", "", "Generated by `tools/build_index.py`. " + legend, f"Records: {len(items)}", ""] + [_line(s, r, "../records") for s, r in items]
            open(os.path.join(idx_dir, f"{st}.md"), "w").write("\n".join(sub) + "\n")
    open(os.path.join(ROOT, "knowledge/INDEX.md"), "w").write("\n".join(out) + "\n")


def sources_index():
    p = os.path.join(ROOT, "sources/INDEX.md")
    head = open(p).read().split(MARK)[0] if os.path.exists(p) else "# Sources index\n\n"
    c = sqlite3.connect(os.path.join(ROOT, "state/ledger.sqlite"))
    stats = c.execute("SELECT status,count(*) FROM items GROUP BY status").fetchall()
    out = [MARK, "", "## Ledger snapshot (generated)", "", "Query details with `python3 tools/ledger.py`.", "",
           "| status | items |", "|---|---|"] + [f"| {s} | {n} |" for s, n in stats]
    out += ["", "### Next 40 unprocessed items by priority", ""]
    for r in c.execute("SELECT id,priority,year,substr(title,1,120) FROM items WHERE status='found' ORDER BY priority DESC, year DESC LIMIT 40"):
        out.append(f"- {r[0]} (p{r[1]}, {r[2]}) {r[3]}")
    out += ["", "### Unreachable", ""]
    for r in c.execute("SELECT id,year,substr(title,1,100),note FROM items WHERE status='unreachable' ORDER BY year DESC"):
        out.append(f"- {r[0]} ({r[1]}) {r[2]} — {r[3]}")
    open(p, "w").write(head.rstrip() + "\n\n" + "\n".join(out) + "\n")


if __name__ == "__main__":
    knowledge_index(); sources_index(); print("indexes rebuilt")
